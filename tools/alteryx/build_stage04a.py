"""Stage 04a - per-person severity fit with the Python tool (scope §6, D6; methodology §8.1).

Runs after 03_burning_cost and before 04_simulate. Native tools prepare the fit data exactly as stage 04 does (units of
bc_adjusted above u = fit_cutoff, else the lowest active PP AP; censored when the uncapped amount reaches the cap);
the Python tool (Designer's base environment: numpy, pandas, scipy) runs tools/python/sevfit.py, embedded verbatim:
left-truncated, right-censored MLE of every candidate in fit_candidates, AIC / BIC / KS, mean excess at the APs,
survival at the diagnostic thresholds, the selection (fit_selected, else lowest AIC among proper fits) and the
selected distribution's inverse-survival grid.

Writes results/out_fit_candidates.csv, out_fit_mean_excess.csv, out_fit_survival.csv, out_sev_table.csv; stage
sev_table (read by stage 04 when severity_source = PYTHON); checks_04a.csv (F01-F06, from the Python tool).
Stage 03 empties these outputs, so stage 04 never uses a fit made on an earlier burning cost (check S07).
"""
from __future__ import annotations

import xol_common as C
from xol_common import X
import build_stage04 as B4

SEVFIT = C.ROOT / "tools/python/sevfit.py"
DRIVER = '''
# ---- driver (generated by tools/alteryx/build_stage04a.py) ----
units, ctx, thr = Alteryx.read("#1"), Alteryx.read("#2"), Alteryx.read("#3")
cand, me, surv, tab, flags = run(units, ctx, thr)
Alteryx.write(cand, 1)
Alteryx.write(me, 2)
Alteryx.write(surv, 3)
Alteryx.write(tab, 4)
Alteryx.write(flags, 5)
'''


def script() -> str:
    return "from ayx import Alteryx\n" + SEVFIT.read_text(encoding="utf-8") + DRIVER


def build(v):
    import results_spec as R
    wf = X.WF("04a_fit_severity", "Stage 04a: severity candidates fitted by the Python tool (truncated, censored MLE)")
    wf.dag = True
    sn = "04a"

    wf.container("04a.1 Fit data: units above u, censoring at caps; thresholds")
    par = C.params_stream(wf, v, ["fit_cutoff", "fit_candidates", "fit_selected"], key="kp", label="parameters")
    lay = B4.pp_layers(wf, v)
    pu = B4.threshold_u(wf, par, lay)
    adj = wf.input_yxdb(C.stage(v, "bc_adjusted"), label="bc_adjusted (stage 03)")
    adj = wf.formula(adj, [("kx", X.INT, "1")], label="key")
    adj = C.append(wf, adj, wf.select(pu, keep=["kp", "u_fit"], keep_unknown=False, label="u"), "kx", "kp", "+ u")
    fu, _ = wf.filter(adj, "[adj] > [u_fit]", label="units above u")
    fu = wf.sort(fu, [("acc_key", "Ascending")], label="fixed order")
    units = wf.select(fu, keep=["adj", "adj_uncapped", "cap"], keep_unknown=False, label="fit units")
    mx = wf.summarize(wf.formula(fu, [("km", X.INT, "1")], label="key"),
                      [("km", "GroupBy", "km"), ("adj", "Max", "max_observed")], label="largest observed")
    ctx = C.append(wf, pu, mx, "kp", "km", "+ largest observed")
    ctx = wf.select(ctx, keep=["u_fit", "max_observed", "p_fit_candidates", "p_fit_selected"],
                    rename={"p_fit_candidates": "fit_candidates", "p_fit_selected": "fit_selected"},
                    keep_unknown=False, label="fit context")
    thr = B4.thresholds(wf, lay)
    thr = wf.formula(thr, [("kt", X.INT, "1")], label="key")
    thr = C.append(wf, thr, wf.select(pu, keep=["kp", "u_fit"], keep_unknown=False, label="u"), "kt", "kp", "+ u")
    thr, _ = wf.filter(thr, "[t] >= [u_fit]", label="thresholds at or above u")
    thr = wf.select(thr, keep=["t", "t_label", "is_ap"], keep_unknown=False, label="thresholds")

    wf.container("04a.2 Python tool: candidates, statistics, selection, inverse-survival grid (tools/python/sevfit.py)")
    py = wf.python([units, ctx, thr], script(), label="severity fit (sevfit.py)")

    wf.container("04a.3 Outputs (typed) and checks")
    for anchor, name in (("Output1", "out_fit_candidates"), ("Output2", "out_fit_mean_excess"),
                         ("Output3", "out_fit_survival")):
        cols = R.SHEETS[name]
        t = wf.select((py, anchor), keep=cols, types={c: R.col_type(c, X) for c in cols},
                      keep_unknown=False, label=f"{name}: types")
        C.result(wf, t, v, name)
    tab = wf.select((py, "Output4"), keep=["k", "lx0", "lx1", "dist"],
                    types={"k": X.INT64, "lx0": X.DBL, "lx1": X.DBL, "dist": X.STR}, keep_unknown=False,
                    label="sev_table: types")
    tab = wf.sort(tab, [("k", "Ascending")], label="by k")
    wf.output_yxdb(tab, C.stage(v, "sev_table"), label="sev_table")
    wf.output_csv(tab, v.p(f"{v.out_dir}/results/out_sev_table.csv"), label="out_sev_table.csv")
    fl = wf.formula((py, "Output5"), [("stage", X.STR, '"S04a"')], label="check records")
    fl = wf.select(fl, keep=C.CHECK_FIELDS, types={f: X.STR for f in C.CHECK_FIELDS}, keep_unknown=False,
                   label="check fields")
    C.finish_checks(wf, [fl], v, sn, chk="04a")
    return C.save(wf, v, "04a_fit_severity.yxmd")


if __name__ == "__main__":
    for v in C.VARIANTS:
        print("wrote", build(v))
